"""Generate frontend wire types: python -m app.local_research.export_types."""
from pathlib import Path
import json

from app.local_research.api import Outcome, Created, Candidates, Confirmed


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return "(" + " | ".join(typescript(v) for v in schema[key]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return f'Array<{typescript(schema["items"])}>'
    if kind == "object":
        if "properties" not in schema:
            return "Record<string, " + typescript(schema.get("additionalProperties", {})) + ">"
        # The additive answer field is optional for compatibility with older briefings.
        return "{ " + "; ".join(json.dumps(k) + ("?: " if k == "answer" and k not in schema.get("required", []) else ": ") + typescript(v)
                                   for k, v in schema["properties"].items()) + " }"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean",
            "null": "null"}.get(kind, "unknown")


def generate():
    definitions = {}
    for model in (Outcome, Created, Candidates, Confirmed):
        schema = model.model_json_schema(mode="serialization")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    return ("// Generated by app.local_research.export_types; do not edit.\n"
            + "\n".join(f"export type {key} = {typescript(value)}" for key, value in definitions.items()) + "\n")


if __name__ == "__main__":
    path = Path(__file__).resolve().parents[3] / "frontend/src/research/contracts.ts"
    path.write_text(generate())
