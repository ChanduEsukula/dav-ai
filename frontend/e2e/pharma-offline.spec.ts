import { expect, test } from '@playwright/test'

test('real frozen release search-to-PDF works with outbound network disabled', async ({ page, request, baseURL }) => {
  expect(process.env.PHARMA_OFFLINE_SMOKE, 'Required release journey must be explicitly enabled; it cannot skip').toBe('1')
  const api = process.env.PHARMA_API_URL || 'http://127.0.0.1:18000'
  const origin = new URL(baseURL!).origin
  const cors = await request.get(`${api}/health`, { headers: { Origin: origin } })
  expect(cors.headers()['access-control-allow-origin'], 'Offline harness must admit the exact Playwright origin').toBe(origin)
  const untrusted = await request.get(`${api}/health`, { headers: { Origin: 'https://untrusted.example' } })
  expect(untrusted.headers()['access-control-allow-origin']).toBeUndefined()
  expect((await request.get(`${api}/ready`)).status(), 'Required artifact is unavailable or unauthorized; release journey is BLOCKED').toBe(200)
  const results = await request.get(`${api}/api/drugs/search?q=Xanax`)
  expect(results.ok()).toBe(true)
  const products = (await results.json()).results
  expect(products.length, 'The actual frozen catalog must contain Xanax').toBeGreaterThan(0)
  const selected = products[0]
  await page.goto('/?q=Xanax')
  await page.getByRole('button', { name: new RegExp('^Select .*' + selected.product_ndcs[0]) }).first().click()
  await expect(page.getByRole('heading', { name: 'Recall history', exact: true })).toBeVisible()
  const sources = page.getByRole('region', { name: 'Sources and data freshness' })
  await expect(sources.getByText('openfda_ndc_directory', { exact: true })).toHaveCount(1)
  await sources.getByText('Stored provenance records (2)').click()
  await expect(sources.getByText('No URL stored for this provenance record.')).toBeVisible()
  await page.getByRole('button', { name: 'Generate PDF Report', exact: true }).click()
  await page.getByLabel('Name (required)').fill('Offline Regression Reader')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Generate and download' }).click()
  const result = await download
  expect(await result.failure()).toBeNull()
  expect(result.suggestedFilename()).toBe('dav-ai-evidence-report.pdf')
  await expect(page.getByRole('status')).toHaveText('Your PDF download is ready.')
})

test('real admitted labels populate the compact card and retain exact source records', async ({ page, request }) => {
  expect(process.env.PHARMA_OFFLINE_SMOKE).toBe('1')
  const api = process.env.PHARMA_API_URL || 'http://127.0.0.1:18000'
  const search = await request.get(`${api}/api/drugs/search?q=0002-0152&limit=1`)
  expect(search.ok()).toBe(true)
  const product = (await search.json()).results[0]
  expect(product.product_ndcs).toContain('0002-0152')
  const response = await request.get(`${api}/api/drugs/${encodeURIComponent(product.id)}/safety/labels`)
  expect(response.ok()).toBe(true)
  const labels = await response.json()
  expect(labels.drug_id).toBe(product.id)
  const selected = labels.records.filter((record: { selection_status: string }) => record.selection_status === 'SELECTED_STORED')
  expect(selected.length).toBeGreaterThan(0)
  await page.goto(`/?q=0002-0152&drug=${encodeURIComponent(product.id)}`)
  const panel = page.getByRole('region', { name: 'Drug labeling', exact: true })
  const fields = ['boxed_warning', 'warnings_and_precautions', 'warnings', 'contraindications', 'adverse_reactions', 'drug_interactions']
  const expected = fields.filter(field => selected.some((record: Record<string, unknown>) => typeof record[field] === 'string' && String(record[field]).trim())).length
  await expect(panel.locator('.label-presence .is-present')).toHaveCount(expected)
  await panel.getByRole('button', { name: 'Expand Drug labeling' }).click()
  await expect(panel.getByText(`Source record: ${selected[0].source_record_id}`, { exact: true })).toBeVisible()
  await expect(panel.getByRole('link', { name: /Official FDA source/ }).first()).toHaveAttribute('href', selected[0].source_url)
  await page.getByRole('button', { name: 'Change selected product' }).click()
  await expect(page.getByRole('heading', { name: 'Select an exact product' })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('button', { name: 'Expand Drug labeling' })).toBeVisible()
})

test('medication discovery precedes exact selection and modes preserve its scope', async ({ page, request }) => {
  expect(process.env.PHARMA_OFFLINE_SMOKE).toBe('1')
  const api = process.env.PHARMA_API_URL || 'http://127.0.0.1:18000'
  const response = await request.get(`${api}/api/medications/overview?q=Xanax`)
  expect(response.ok()).toBe(true)
  const overview = await response.json()
  expect(overview.matched_product_count).toBe(9)
  expect(overview.labels.distinct_admitted_records).toBe(1)
  expect(overview.recalls.distinct_linked_records).toBe(2)
  expect(overview.ingredients[0].report_count).toBe(18)
  await page.goto('/?q=Xanax')
  await expect(page.getByText('9 matching products · 6 stored formulation identifiers', { exact: true })).toBeVisible()
  await expect(page.getByText('Subpotent Drug', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('Failed Dissolution Specifications', { exact: true }).first()).toBeVisible()
  await expect(page.locator('.compact-product-row')).toHaveCount(9)
  const summaries = page.locator('.medication-overview-panels .evidence-panel-summary')
  expect(await summaries.evaluateAll(nodes => nodes.every(node => node.scrollHeight <= node.clientHeight + 1)),
    'Summary caveats must remain visible without internal scrolling').toBe(true)
  const cards = await page.locator('.medication-overview-panels .evidence-glass-panel').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().height))
  expect(Math.max(...cards) - Math.min(...cards)).toBeLessThan(2)
  const before = await page.locator('.medication-overview-panels').boundingBox()
  await page.getByRole('button', { name: 'Research Pro', exact: true }).click()
  await expect(page.locator('.glass-site')).toHaveAttribute('data-theme', 'research_pro')
  await expect(page.getByRole('table')).toBeVisible()
  await expect(page.getByLabel('Sort products')).toBeVisible()
  await expect(page).toHaveURL(/q=Xanax/)
  const after = await page.locator('.medication-overview-panels').boundingBox()
  expect(after!.width).toBeCloseTo(before!.width, 0)
  await page.getByRole('button', { name: /^Select .*NDC/ }).first().click()
  const selectedUrl = page.url()
  await page.getByRole('button', { name: 'Everyday', exact: true }).click()
  await expect(page).toHaveURL(selectedUrl)
  await expect(page.getByRole('button', { name: 'Expand Drug labeling' })).toBeVisible()
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Operational Overview', exact: true }).click()
  await expect(page.locator('.flow-stage')).toHaveCount(4)
  await page.getByRole('button', { name: 'Research Pro', exact: true }).click()
  await expect(page.locator('.flow-stage')).toHaveCount(5)
  await page.reload()
  await expect(page.locator('.glass-site')).toHaveAttribute('data-theme', 'research_pro')
})
