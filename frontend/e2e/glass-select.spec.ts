import { expect,test } from '@playwright/test'
import overview from '../src/test/medication-overview.fixture.json' with {type:'json'}
for(const mode of ['Everyday','Research Pro']) {
 test(`${mode} glass filters preserve values and support keyboard and outside dismissal`,async({page})=>{
  await page.route('**/api/medications/overview?*',route=>route.fulfill({json:overview}))
  await page.route('**/api/drugs/search?*',route=>route.fulfill({json:{results:overview.products,count:9}}))
  await page.goto('/?q=Xanax')
  await page.getByRole('button',{name:mode,exact:true}).click()
  const strength=page.getByRole('combobox',{name:'Strength',exact:true})
  await strength.scrollIntoViewIfNeeded();await strength.focus();await page.keyboard.press('Space')
  await expect(page.getByRole('listbox')).toBeVisible()
  await expect(page.getByRole('option',{name:'All strengths'})).toBeFocused()
  await page.keyboard.press('Home')
  await expect(page.getByRole('option',{name:'All strengths'})).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('option',{name:'0.25 mg / 1'})).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(strength).toContainText('0.25 mg / 1')
  await expect(page.getByRole('button',{name:/^Select .*NDC/})).toHaveCount(2)
  await expect(strength).toBeFocused()
  await strength.click()
  await expect(page.getByRole('option',{name:'0.25 mg / 1'})).toHaveAttribute('data-state','checked')
  await expect(page.getByRole('option',{name:'0.25 mg / 1'}).locator('.glass-select-check')).toBeVisible()
  await page.keyboard.press('Escape');await expect(strength).toBeFocused()
  await strength.click();await page.getByRole('option',{name:'All strengths'}).click()
  await expect(page.getByRole('button',{name:/^Select .*NDC/})).toHaveCount(9)
  const form=page.getByRole('combobox',{name:'Dosage form',exact:true})
  await form.click()
  await expect(page.getByRole('option',{name:'All forms'})).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('option',{name:'TABLET',exact:true})).toBeFocused()
  await page.keyboard.press('Space')
  await expect(form).toContainText('TABLET')
  await form.click();await expect(page.getByRole('option',{name:'TABLET',exact:true})).toBeFocused()
  await page.keyboard.press('End')
  await expect(page.getByRole('option',{name:'TABLET, EXTENDED RELEASE',exact:true})).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button',{name:/^Select .*NDC/})).toHaveCount(2)
  await form.click()
  await expect(page.getByRole('option',{name:'TABLET, EXTENDED RELEASE',exact:true})).toBeFocused()
  await expect(page.getByRole('listbox')).toHaveCSS('opacity','1')
  await page.mouse.click(8,500)
  await expect(page.getByRole('listbox')).toHaveCount(0)
  if(mode==='Everyday') {await page.getByText('More product filters',{exact:true}).click();await expect(page.locator('.advanced-filter-toolbar')).toBeVisible()}
  await page.getByLabel('Product or package NDC').fill('58151-505')
  await expect(page.getByRole('button',{name:/^Select .*NDC/})).toHaveCount(1)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 })
}

test('touch menus stay within the viewport, above glass layers, and respect reduced motion',async({browser})=>{
 const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,reducedMotion:'reduce'})
 const page=await context.newPage()
 await page.route('**/api/medications/overview?*',route=>route.fulfill({json:overview}))
 await page.route('**/api/drugs/search?*',route=>route.fulfill({json:{results:overview.products,count:9}}))
 await page.goto('http://127.0.0.1:15173/?q=Xanax')
 for(const mode of ['Everyday','Research Pro']) {
  await page.getByRole('button',{name:mode,exact:true}).tap()
  for(const name of ['Strength','Dosage form']) {
   const trigger=page.getByRole('combobox',{name,exact:true})
   await trigger.scrollIntoViewIfNeeded();await page.evaluate(()=>window.scrollBy(0,-180));await trigger.tap()
   const menu=page.getByRole('listbox');await expect(menu).toBeVisible()
   const box=await menu.boundingBox()
   expect(box!.x).toBeGreaterThanOrEqual(11);expect(box!.x+box!.width).toBeLessThanOrEqual(379)
   expect(box!.y).toBeGreaterThanOrEqual(0);expect(box!.y+box!.height).toBeLessThanOrEqual(833)
   expect(await menu.evaluate(node=>getComputedStyle(node).animationName)).toBe('none')
   expect(await menu.evaluate(node=>{const r=node.getBoundingClientRect();return node.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2))})).toBe(true)
   await page.getByRole('option',{name:name==='Strength'?'0.25 mg / 1':'TABLET',exact:true}).tap()
   await expect(trigger).toContainText(name==='Strength'?'0.25 mg / 1':'TABLET')
  }
 }
 await context.close()
})
